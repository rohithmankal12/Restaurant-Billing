const { app, BrowserWindow, ipcMain } = require('electron');
const path = require('node:path');
const fs = require('node:fs');
const os = require('node:os');
const { openStore } = require('./store.cjs');
const { SystemDriverPrinter } = require('./printer.cjs');

let store;
app.whenReady().then(async () => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'counter-smoke-'));
  store = await openStore(path.join(dir, 'smoke.sqlite'));
  store.setupAuth('owner', 'secure-pass-123');
  let authenticated = false;
  ipcMain.handle('authStatus', () => ({ ...store.authStatus(), authenticated }));
  ipcMain.handle('setupAuth', (_, username, password) => { const result = store.setupAuth(username, password); authenticated = true; return result; });
  ipcMain.handle('login', (_, username, password) => { if (username !== 'owner' || password !== 'secure-pass-123') throw Error('Invalid username or password.'); authenticated = true; return { ok: true }; });
  ipcMain.handle('logout', () => { authenticated = false; return { ok: true }; });
  for (const name of ['snapshot', 'saveMenu', 'deleteMenu', 'saveSettings', 'saveDraft', 'checkout', 'cancelInvoice']) {
    ipcMain.handle(name, (_, ...args) => store[name](...args));
  }
  ipcMain.handle('dataPath', () => store.file);
  ipcMain.handle('printers', () => []);
  ipcMain.handle('print', () => new Promise((_, reject) => setTimeout(() => reject(Error('Simulated printer callback failure')), 300)));
  const window = new BrowserWindow({
    show: false,
    webPreferences: { preload: path.join(__dirname, 'preload.cjs'), contextIsolation: true, nodeIntegration: false, sandbox: true },
  });
  await window.loadFile(path.join(__dirname, '../dist/browser/index.html'));
  await new Promise(resolve => setTimeout(resolve, 500));
  fs.writeFileSync(path.join(os.tmpdir(), 'counter-home.png'), (await window.webContents.capturePage()).toPNG());
  const result = await window.webContents.executeJavaScript(`(async () => {
    const wait = ms => new Promise(resolve => setTimeout(resolve, ms));
    const input = (element, value) => { element.value = value; element.dispatchEvent(new Event('input', { bubbles: true })); };
    if (!document.body.innerText.includes('Welcome back')) throw Error('Login page did not render');
    input(document.querySelector('input[name="username"]'), 'owner');
    input(document.querySelector('input[name="password"]'), 'secure-pass-123');
    await wait(100);
    document.querySelector('form').dispatchEvent(new Event('submit', { bubbles: true, cancelable: true }));
    await wait(500);
    if (!document.body.innerText.includes('Restaurant overview')) throw Error('Home page did not render');
    [...document.querySelectorAll('.action-card')].find(button => button.innerText.includes('New Invoice')).click();
    await wait(100);
    const search = document.querySelector('#item-search');
    search.focus();
    await wait(50);
    if (document.querySelector('.suggestions')) throw Error('Empty item search displayed suggestions');
    input(search, 'CB');
    await wait(100);
    if (document.querySelectorAll('.suggestions button').length > 4) throw Error('Item search displayed more than four suggestions');
    if (!document.querySelector('.suggestions')?.innerText.includes('Chicken Biryani')) throw Error('CB shortcut did not suggest Chicken Biryani');
    search.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
    await wait(100);
    const portion = document.querySelector('.entry-row select');
    if (document.activeElement !== portion) throw Error('Selecting an item did not focus the portion column');
    const focusables = [...document.querySelectorAll('input:not([disabled]), select:not([disabled]), button:not([disabled])')];
    if (focusables[focusables.indexOf(portion) + 1] !== document.querySelector('#entry-qty')) throw Error('Quantity is not next after portion');
    portion.dispatchEvent(new KeyboardEvent('keydown', { key: 'Enter', bubbles: true }));
    if (document.activeElement !== document.querySelector('#entry-qty')) throw Error('Enter on portion did not focus quantity');
    document.querySelector('.add-row').click();
    await wait(100);
    const deleteButton = document.querySelector('.saved-row .delete-row').getBoundingClientRect();
    const invoiceCard = document.querySelector('.invoice-workspace').getBoundingClientRect();
    if (deleteButton.right > invoiceCard.right + 1) throw Error('Invoice delete button overflowed its card');
    input(search, 'Chic');
    await wait(100);
    if (!document.querySelector('.suggestions')?.innerText.includes('Chicken Biryani')) throw Error('Chic prefix did not suggest Chicken Biryani');
    document.querySelector('.suggestions button').click();
    await wait(100);
    if (document.activeElement !== document.querySelector('.entry-row select')) throw Error('Clicking an item did not focus the portion column');
    input(search, '');
    search.dispatchEvent(new Event('blur', { bubbles: true }));
    await wait(100);
    document.querySelector('.checkout').click();
    await wait(500);
    const renderedInvoiceNumber = document.querySelector('.receipt h2')?.innerText || '';
    if (!renderedInvoiceNumber.match(/^[0-9]{4}-01$/)) throw Error('Checkout or daily invoice numbering failed: ' + renderedInvoiceNumber);
    const cancelButton = [...document.querySelectorAll('.receipt button')].find(button => button.innerText.includes('Cancel bill'));
    if (!cancelButton || cancelButton.disabled) throw Error('Cancel bill should be available without a reason');
    const invoiceNumber = document.querySelector('.receipt h2').innerText;
    document.querySelector('.receipt .primary').click();
    await wait(50);
    if (document.querySelector('.receipt')) throw Error('Receipt popup did not close immediately');
    await wait(350);
    if (document.querySelector('.receipt')) throw Error('Receipt popup reopened after printer failure');
    [...document.querySelectorAll('nav button')].find(button => button.innerText.includes('Overview')).click();
    await wait(100);
    if (!document.querySelector('.top-items-panel')?.innerText.includes('Chicken Biryani')) throw Error('Today item sales did not include the sold item');
    document.querySelector('.top-items-panel .link').click();
    await wait(100);
    if (!document.body.innerText.includes('Daily item-wise sales') || !document.querySelector('.report-item-row')?.innerText.includes('Chicken Biryani')) throw Error('Item-wise sales report did not render');
    [...document.querySelectorAll('nav button')].find(button => button.innerText.includes('Menu library')).click();
    await wait(100);
    const menuRowsBefore = document.querySelectorAll('tbody tr').length;
    window.confirm = () => true;
    document.querySelector('.danger-button').click();
    await wait(150);
    if (document.querySelectorAll('tbody tr').length !== menuRowsBefore - 1) throw Error('Menu item was not deleted');
    return { login: true, home: true, shortcut: true, prefix: true, checkout: true, printClosed: true, itemReports: true, menuDelete: true, invoice: invoiceNumber };
  })()`);
  fs.writeFileSync(path.join(os.tmpdir(), 'counter-invoice.png'), (await window.webContents.capturePage()).toPNG());
  const savedInvoice = store.snapshot().invoices[0];
  const pdfDirectory = process.env.COUNTER_PDF_QA_DIR || dir;
  const pdf = await new SystemDriverPrinter().savePdf(savedInvoice, store.settings(), pdfDirectory);
  if (!fs.readFileSync(pdf.savedPath).subarray(0, 4).equals(Buffer.from('%PDF'))) throw Error('PDF receipt was not created');
  result.pdf = path.basename(pdf.savedPath);
  console.log(JSON.stringify(result));
  store.close();
  window.destroy();
  fs.rmSync(dir, { recursive: true, force: true });
  app.exit(0);
}).catch(error => {
  console.error(error);
  store?.close();
  app.exit(1);
});
